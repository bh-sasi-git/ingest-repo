CREATE OR REPLACE PROCEDURE raw_to_silver_orders_merge_261105_63e8()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
BEGIN
    BEGIN TRANSACTION;

    MERGE INTO SF_BIGHAMMER.SILVER.FCT_ORDERS_SS AS target
    USING (
    WITH RAW_ORDERS AS (
        SELECT ORDER_ID AS ORDER_ID_src_1, CUSTOMER_ID AS CUSTOMER_ID_src_1, STORE_ID AS STORE_ID_src_1, AMOUNT AS AMOUNT_src_1, STATUS AS STATUS_src_1, UPDATED_AT AS UPDATED_AT_src_1 FROM SF_BIGHAMMER.RAW.RAW_ORDERS
    ),
    filter_completed_orders AS (
        SELECT * FROM RAW_ORDERS WHERE STATUS_src_1 = 'COMPLETED'
    ),
    FCT_ORDERS_SS_rename AS (
        SELECT ORDER_ID_src_1 AS ORDER_ID, CUSTOMER_ID_src_1 AS CUSTOMER_ID, STORE_ID_src_1 AS STORE_ID, AMOUNT_src_1 AS AMOUNT, STATUS_src_1 AS STATUS, UPDATED_AT_src_1 AS UPDATED_AT FROM filter_completed_orders
    ),
    FCT_ORDERS_SS_final AS (
        SELECT ORDER_ID, CUSTOMER_ID, STORE_ID, AMOUNT, STATUS, UPDATED_AT FROM FCT_ORDERS_SS_rename
    )
    SELECT ORDER_ID, CUSTOMER_ID, STORE_ID, AMOUNT, STATUS, UPDATED_AT FROM FCT_ORDERS_SS_final
    ) AS source
    ON target.ORDER_ID = source.ORDER_ID
    WHEN MATCHED THEN UPDATE SET target.CUSTOMER_ID = source.CUSTOMER_ID, target.STORE_ID = source.STORE_ID, target.AMOUNT = source.AMOUNT, target.STATUS = source.STATUS, target.UPDATED_AT = source.UPDATED_AT
    WHEN NOT MATCHED THEN INSERT (ORDER_ID, CUSTOMER_ID, STORE_ID, AMOUNT, STATUS, UPDATED_AT) VALUES (source.ORDER_ID, source.CUSTOMER_ID, source.STORE_ID, source.AMOUNT, source.STATUS, source.UPDATED_AT);

    COMMIT;

    RETURN 'Success';
EXCEPTION
  WHEN OTHER THEN
    ROLLBACK;
    RAISE;
END
$$;